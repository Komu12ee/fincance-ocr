'use strict';

/**
 * Central config — every env-var read happens here.
 * server.js and route files import from this module.
 */

// Load the repo-root .env (single source of truth). When this server is spawned
// by the selection launcher it already inherits the env, so dotenv only fills in
// gaps (it never overrides an existing process.env value).
try {
  const path = require('path');
  require('dotenv').config({ path: path.join(__dirname, '..', '..', '..', '.env') });
} catch (_) {
  // dotenv is optional — ignore if not installed
}

// ── Required secrets ────────────────────────────────────────────────────────
const JWT_SECRET = process.env.JWT_SECRET;
if (!JWT_SECRET) {
  console.error('[config] FATAL: JWT_SECRET env var is not set. Refusing to start.');
  process.exit(1);
}

// ── User store ──────────────────────────────────────────────────────────────
// Users are defined as  USER_<NAME>=<bcrypt-hash>  in the environment.
// Example .env line (generated by scripts/add-user.js):
//   USER_ojash=$2b$10$...
//
// Username matching is case-insensitive.
function loadUsers() {
  const users = {};
  for (const [key, value] of Object.entries(process.env)) {
    if (key.startsWith('USER_')) {
      const username = key.slice(5).toLowerCase();
      users[username] = value; // value is the bcrypt hash
    }
  }
  return users;
}

// ── Branding ────────────────────────────────────────────────────────────────
// Which department this instance serves. The selection launcher passes PIPELINE
// in the spawn env; falls back to chips for a standalone `node server.js`.
// Display strings live in pipelines.json so Node and Python read one source.
const PIPELINE = (process.env.PIPELINE || 'chips').toLowerCase();

function loadBranding() {
  const fallback = {
    pipeline: PIPELINE,
    label: 'Document Assistant',
    shortLabel: PIPELINE.toUpperCase(),
    org: 'Government of Chhattisgarh',
    subtitle: 'Document Assistant',
    logo: '',
  };
  try {
    const path = require('path');
    const registry = require(path.join(__dirname, '..', '..', '..', 'pipelines.json'));
    const cfg = registry[PIPELINE];
    if (!cfg) return fallback;
    return {
      pipeline: PIPELINE,
      label: cfg.label || fallback.label,
      shortLabel: cfg.shortLabel || fallback.shortLabel,
      org: cfg.org || fallback.org,
      subtitle: cfg.subtitle || fallback.subtitle,
      logo: cfg.logo || '',
    };
  } catch (err) {
    console.warn(`[config] Could not read branding for "${PIPELINE}": ${err.message}`);
    return fallback;
  }
}

module.exports = {
  PORT:      parseInt(process.env.PORT      || '3000', 10),
  FLASK_URL: process.env.FLASK_URL           || 'http://localhost:5000',
  IS_PROD:   process.env.NODE_ENV            === 'production',
  JWT_SECRET,
  JWT_EXPIRY: process.env.JWT_EXPIRY         || '8h',
  PIPELINE,
  BRANDING: loadBranding(),
  loadUsers,
};
